// Lesson 03 - Whole numbers
// Goal: store whole numbers in variables.

#include <iostream>

int main()
{
    int age = 20;
    int marks = 75;
    int total = age + marks;

    std::cout << "Age: " << age << "\n";
    std::cout << "Marks: " << marks << "\n";
    std::cout << "Total: " << total << "\n";
    return 0;
}

